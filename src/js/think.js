    if(/^(اره|آره|بله|باشه|اوکی|ok|حتما|حتماً|چشم|ممنونم|خب|خوبه|عالیه|میشه|اها|آها)/.test(q))return ktPick(['عالی! 💪 همین را شروع کن و بعد از اتمامش بگو چطور بود.','خوبه! قدم اول را بردار؛ هر وقت خواستی ادامه‌اش را با هم بچینیم. 🌱']);
